"""Turn one run's ArmorIQ decisions into an auditor-friendly evidence document.

A starting point for evidence, not a certification. Control references are to the
AICPA Trust Services Criteria (SOC 2) by ID only.
"""

from __future__ import annotations

import datetime as dt


def _fmt_args(args: dict) -> str:
    return ", ".join(f"{k}={v!r}" for k, v in (args or {}).items() if not str(k).startswith("_"))[:160]


def evidence_markdown(run: dict) -> str:
    when = dt.datetime.fromtimestamp(run["started"], dt.timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    d = run["decisions"]
    by = lambda v: [x for x in d if x["verdict"] == v]  # noqa: E731
    lines = [
        f"# Foreman evidence pack, run {run['id']}",
        "",
        f"- Requested by: {run['actor']['name']} ({run['actor']['email']}), {run['actor']['role']}",
        f"- When: {when}",
        f"- Request: \"{run['goal']}\"",
        f"- Guarded by ArmorIQ: {'yes' if run['guarded'] else 'NO (unguarded comparison run)'}",
        "",
        "## Signed work orders (ArmorIQ intent tokens)",
        "",
        "| Worker | Tools signed | Plan hash | Plan ID |",
        "|---|---|---|---|",
    ]
    for w, t in run["tokens"].items():
        lines.append(f"| {w} | {', '.join(t['tools'])} | `{t['plan_hash'][:16]}…` | `{t['plan_id']}` |")
    lines += ["", "## Every tool call and its decision", "", "| Worker | Tool | Arguments | Decision | Reason |", "|---|---|---|---|---|"]
    for x in d:
        lines.append(f"| {x['worker']} | {x['tool']} | {_fmt_args(x['args'])} | **{x['verdict'].upper()}** | {x['reason']} |")
    lines += [
        "",
        "## Controls this run gives evidence for",
        "",
        f"- **CC6.1 Logical access.** Each worker could only use the tools in its own signed slice. "
        f"{len([x for x in by('blocked') if 'work order' in x['reason']])} out-of-slice call(s) were refused.",
        f"- **CC6.3 Role-based authorization.** Calls ran on behalf of {run['actor']['email']}, and per-user policy was applied to each.",
        f"- **CC7.2 Monitoring for anomalies.** {len(by('blocked'))} blocked call(s) are recorded above with reasons, "
        "and also in the ArmorIQ audit log.",
        f"- **CC8.1 Authorization of changes.** {len(by('approved')) + len(by('held')) + len(by('rejected'))} call(s) "
        "needed a human decision before running.",
        "",
        "_Generated by Foreman from ArmorIQ decisions. Cross-check plan IDs in the ArmorIQ console._",
    ]
    return "\n".join(lines) + "\n"
